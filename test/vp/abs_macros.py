#!/usr/bin/env python3
r"""abs_macros.py IN.tex OUT.tex -- emit a magnitude twin \<name>Abs for every numeric \newcommand in IN.tex.

The headline macros carry signed deltas (negative = better). Prose that says "reduces latency by X%" needs the
magnitude, and hardcoding it would break the provenance chain paper_table.py --verify enforces. This derives the
magnitude from the same generated file, so a regenerated number propagates to both forms.
"""
import re, sys

src, dst = sys.argv[1], sys.argv[2]
out = ["%% GENERATED by abs_macros.py from %s -- do not edit by hand." % src.split("/")[-1]]
pat = re.compile(r"\\newcommand\{\\([A-Za-z]+)\}\{([+-]?[0-9]*\.?[0-9]+)\}")
n = 0
for m in pat.finditer(open(src).read()):
    name, val = m.group(1), m.group(2)
    out.append(f"\\newcommand{{\\{name}Abs}}{{{val.lstrip(chr(43)).lstrip(chr(45))}}}")   # keep the source's own precision
    n += 1
open(dst, "w").write("\n".join(out) + "\n")
print(f"  {n} magnitude macros -> {dst}")
