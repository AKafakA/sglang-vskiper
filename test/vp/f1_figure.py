#!/usr/bin/env python3
"""Figure 1 (fig:f1-motivation): the public FlexiDepth checkpoint against its base model in a standard HF generation loop,
decode throughput at batch sizes 1 and 8 -- FLOPs saved, time lost. v1.8 (owner, D-849 add. 36): three runs instead of one;
the bars are the mean over runs, the whiskers the range, and the drop is computed from the means.

Same protocol, style and macro names as the v1.5 producer (vPipe-doc/paper/figs/make_figures.py, F1 block): 100 prompts x 256
greedy tokens per run, `f1_<model>_bs<bs>.json` per run directory, `decode_tok_per_s` the reading.

usage: f1_figure.py <run dir> [<run dir> ...] --pdf figures/f1_flops_vs_wallclock.pdf --macros generated/f1_macros.tex
"""
from __future__ import annotations

import argparse
import json
import statistics
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

C_LARGEST = "#0072B2"
C_VANILLA = "#555555"
GRID_KW = dict(axis="y", linewidth=0.4, alpha=0.35, zorder=0)
DET_META = {"CreationDate": None}
PROMPTS, TOKENS = 100, 256
WORD = {1: "One", 8: "Eight"}


def load(run: Path, model: str, bs: int) -> float:
    p = run / f"f1_{model}_bs{bs}.json"
    if not p.is_file():
        sys.exit(f"FATAL: missing F1 result {p}")
    d = json.loads(p.read_text())
    if d.get("batch_size") != bs or d.get("n_prompts") != PROMPTS or d.get("new_tokens_per_req") != TOKENS:
        sys.exit(f"FATAL: {p} protocol mismatch (batch {d.get('batch_size')}, prompts {d.get('n_prompts')}, tokens {d.get('new_tokens_per_req')})")
    return float(d["decode_tok_per_s"])


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("runs", nargs="+", type=Path)
    ap.add_argument("--pdf", type=Path, required=True)
    ap.add_argument("--macros", type=Path, required=True)
    ap.add_argument("--flexidepth-label", default="FlexiDepth\n(${\\approx}25\\%$ FLOPs saved)",
                    help="x tick label of the checkpoint bar (the v1.5 figure's wording by default)")
    a = ap.parse_args()
    tp = {(m, bs): [load(r, m, bs) for r in a.runs] for m in ("vanilla", "flexidepth") for bs in (1, 8)}
    mean = {k: statistics.mean(v) for k, v in tp.items()}
    drop = {bs: 100.0 * (1.0 - mean[("flexidepth", bs)] / mean[("vanilla", bs)]) for bs in (1, 8)}
    per_run = {bs: [100.0 * (1.0 - f / v) for v, f in zip(tp[("vanilla", bs)], tp[("flexidepth", bs)])] for bs in (1, 8)}
    for bs in (1, 8):
        print(f"  bs={bs}: vanilla {mean[('vanilla', bs)]:.2f} vs FlexiDepth {mean[('flexidepth', bs)]:.2f} tok/s over {len(a.runs)} runs "
              f"-> drop {drop[bs]:.1f}% (per run {', '.join(f'{x:.1f}' for x in per_run[bs])})")
    macros = [f"\\newcommand{{\\vpFOneDropBs{WORD[bs]}}}{{{drop[bs]:.1f}}}" for bs in (1, 8)]
    macros += [f"\\newcommand{{\\vpFOneDropBs{WORD[bs]}Min}}{{{min(per_run[bs]):.1f}}}" for bs in (1, 8)]
    macros += [f"\\newcommand{{\\vpFOneDropBs{WORD[bs]}Max}}{{{max(per_run[bs]):.1f}}}" for bs in (1, 8)]
    macros += [f"\\newcommand{{\\vpFOnePrompts}}{{{PROMPTS}}}", f"\\newcommand{{\\vpFOneTokens}}{{{TOKENS}}}",
               f"\\newcommand{{\\vpFOneRuns}}{{{len(a.runs)}}}"]
    a.macros.write_text("% GENERATED by f1_figure.py: Figure 1, mean over runs\n" + "\n".join(macros) + "\n")

    plt.rcParams.update({"font.family": "serif", "font.serif": ["TeX Gyre Termes", "STIX Two Text", "Times New Roman", "Nimbus Roman", "DejaVu Serif"],
                         "mathtext.fontset": "stix", "font.size": 7, "axes.titlesize": 7, "axes.labelsize": 7, "xtick.labelsize": 6.5,
                         "ytick.labelsize": 6.5, "axes.linewidth": 0.6, "xtick.major.width": 0.6, "ytick.major.width": 0.6,
                         "xtick.major.size": 2.0, "ytick.major.size": 2.0, "axes.spines.top": False, "axes.spines.right": False,
                         "pdf.fonttype": 42, "savefig.dpi": 300})
    fig, axes = plt.subplots(1, 2, figsize=(3.35, 1.62), constrained_layout=True)
    for ax, bs in zip(axes, (1, 8)):
        van, flx = mean[("vanilla", bs)], mean[("flexidepth", bs)]
        err = [[m - min(tp[(k, bs)]) for k, m in (("vanilla", van), ("flexidepth", flx))],
               [max(tp[(k, bs)]) - m for k, m in (("vanilla", van), ("flexidepth", flx))]]
        ax.bar([0, 1], [van, flx], 0.62, color=[C_VANILLA, C_LARGEST], linewidth=0, zorder=3,
               yerr=err, error_kw=dict(elinewidth=0.6, capsize=1.5, ecolor="#222222", zorder=4))
        ax.axhline(van, color=C_VANILLA, linestyle="--", linewidth=0.8, zorder=2)
        for x, v in ((0, van), (1, flx)):
            ax.annotate(f"{v:.1f}", xy=(x, max(tp[("vanilla" if x == 0 else "flexidepth", bs)])), xytext=(0, 1.5),
                        textcoords="offset points", ha="center", va="bottom", fontsize=6, color="#222222")
        ax.annotate(f"{-drop[bs]:+.1f}%", xy=(1, flx / 2), ha="center", va="center", fontsize=6.5, color="white", fontweight="bold")
        ax.set_xticks([0, 1])
        ax.set_xticklabels(["Vanilla", a.flexidepth_label], fontsize=6)
        ax.set_title("(a) batch size 1" if bs == 1 else "(b) batch size 8", pad=3)
        ax.set_ylim(0, van * 1.18)
        ax.grid(**GRID_KW)
    axes[0].set_ylabel("Decode throughput (tok/s)")
    a.pdf.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(a.pdf, metadata=DET_META)
    plt.close(fig)
    print(f"  wrote {a.pdf} and {a.macros} ({len(macros)} macros)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
