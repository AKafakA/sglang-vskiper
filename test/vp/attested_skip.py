#!/usr/bin/env python3
"""The skip ratio a served arm actually ran, per phase, read from its attestation.

    attested_skip.py --cell Qwen=<root>/server_info.after.json ... --macros out.tex

`full_graph_routes.by_phase.<decode|prefill>.skip_ratio` is project_rows / layer_rows over every
routed-layer decision the server made in that phase: the fraction of decisions that took the cheap
path. It is what the checkpoint did on this suite under this arm, as opposed to what its training
target declared, and the two are compared in the Qwen appendix. Emits, per label,
\\vp<Label>SDecode and \\vp<Label>SPrefill to three decimals; --engagement-range adds the prefill
engagement estimate the regime switch held at the end of each listed cell, as a min/max pair. Fails on a snapshot with no vp_runtime
(an upstream arm has nothing to attest) or with a phase that made no decision.
"""
import argparse
import json
import re
import sys


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--cell", action="append", default=[], required=True, help="Label=path/to/server_info.after.json")
    ap.add_argument("--engagement-range", action="append", default=[],
                    help="Label=snap1,snap2,...: the regime switch's prefill engagement estimate (EMA) at the "
                         "end of each listed cell, emitted as \\vp<Label>PrefillEngagementMin / Max (2 decimals)")
    ap.add_argument("--macros", required=True)
    args = ap.parse_args()
    lines = ["% GENERATED by attested_skip.py: per-phase skip ratio from the served arm's attestation"]
    for spec in args.cell:
        label, path = spec.split("=", 1)
        if not re.fullmatch(r"[A-Za-z]+", label):
            sys.exit(f"FATAL: label {label!r} must be letters only (it becomes a macro name)")
        info = json.load(open(path))
        states = info.get("internal_states") or []
        vp = states[0].get("vp_runtime") if states else None
        if not vp:
            sys.exit(f"FATAL {path}: no vp_runtime block -- nothing to attest (an upstream arm?)")
        phases = vp["model"]["flexidepth"]["full_graph_routes"]["by_phase"]
        for phase, name in (("decode", "SDecode"), ("prefill", "SPrefill")):
            rec = phases[phase]
            if rec["layer_rows"] == 0:
                sys.exit(f"FATAL {path}: phase {phase} made no routed-layer decision")
            lines.append(f"\\newcommand{{\\vp{label}{name}}}{{{rec['project_rows'] / rec['layer_rows']:.3f}}}")
    for spec in args.engagement_range:
        label, paths = spec.split("=", 1)
        if not re.fullmatch(r"[A-Za-z]+", label):
            sys.exit(f"FATAL: label {label!r} must be letters only (it becomes a macro name)")
        emas = []
        for path in paths.split(","):
            info = json.load(open(path))
            states = info.get("internal_states") or []
            vp = states[0].get("vp_runtime") if states else None
            if not vp:
                sys.exit(f"FATAL {path}: no vp_runtime block -- nothing to attest")
            est = vp["regime_switch"]["counters"]["prefill_engagement"]
            if est["samples"] == 0:
                sys.exit(f"FATAL {path}: the prefill engagement estimate took no sample")
            emas.append(est["ema"])
        lines.append(f"\\newcommand{{\\vp{label}PrefillEngagementMin}}{{{min(emas):.2f}}}")
        lines.append(f"\\newcommand{{\\vp{label}PrefillEngagementMax}}{{{max(emas):.2f}}}")
    open(args.macros, "w").write("\n".join(lines) + "\n")
    print(f"  {len(lines) - 1} attested-skip macros -> {args.macros}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
