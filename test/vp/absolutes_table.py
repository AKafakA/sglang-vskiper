#!/usr/bin/env python3
"""Absolute baseline numbers per headline row (reviewer W7), from paired_report.json.

Emits LaTeX rows: dataset, rate label, upstream TTFT mean (ms), TPOT mean (ms), E2E mean (s),
makespan (s), output tok/s — the numbers a systems reader needs beside the relative table.
Usage: absolutes_table.py paired_report.json --knee gsm8k=11 --knee bbh_cot=25 --knee coqa=27 --out rows.tex
"""
from __future__ import annotations
import argparse, json, sys
from pathlib import Path

NAMES = {"gsm8k": "GSM8K", "bbh_cot": "BBH", "coqa": "CoQA"}
COLS = [("TTFT mean", 1.0, "{:.0f}"), ("TPOT mean", 1.0, "{:.1f}"), ("E2E mean", 1e-3, "{:.1f}"),
        ("makespan", 1.0, "{:.0f}"), ("drain", 1.0, "{:.0f}"), ("output TPS", 1.0, "{:.0f}"), ("injected rate", 1.0, "{:.1f}")]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("report", type=Path)
    ap.add_argument("--knee", action="append", default=[], metavar="DS=QSTAR")
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--macros", type=Path, default=None)
    a = ap.parse_args()
    knees = {k: float(v) for k, v in (x.split("=", 1) for x in a.knee)}
    rows = json.loads(a.report.read_text())["rows"]
    by = {}
    for r in rows:
        by.setdefault((r["dataset"], r["suite"]), {})[r["metric"]] = r
    MACRO_DS = {"gsm8k": "Gsm", "bbh_cot": "Bbh", "coqa": "Coqa"}
    MACRO_RATE = {"0.75": "Low", "0.95": "Mid", "1.25": "High"}
    MACRO_METRIC = {"TTFT mean": "TTFT", "TPOT mean": "TPOT", "E2E mean": "EtoE", "makespan": "Makespan",
                    "output TPS": "TPS", "drain": "Drain", "injected rate": "Injected"}
    out, macros = [], ["% GENERATED by test/vp/absolutes_table.py -- upstream absolutes (ms / s / tok/s)."]

    def rate_of(suite: str) -> float:
        return float(suite.split("_r")[-1].replace("p", "."))

    order = sorted(by.items(), key=lambda kv: (list(NAMES).index(kv[0][0]) if kv[0][0] in NAMES else 9,
                                               rate_of(kv[0][1])))
    for (ds, suite), m in order:
        rate = rate_of(suite)
        frac = f"{rate/knees[ds]:.2f}" if ds in knees else "--"
        cells = []
        for metric, scale, fmt in COLS:
            r = m.get(metric)
            if r is None or r.get("baseline_abs") is None:
                sys.exit(f"{ds} {suite}: no absolute for {metric} (re-run paired_analysis)")
            value = fmt.format(r["baseline_abs"] * scale)
            cells.append(value)
            if ds in MACRO_DS and frac in MACRO_RATE:
                macros.append(f"\\newcommand{{\\vpAbs{MACRO_METRIC[metric]}{MACRO_DS[ds]}{MACRO_RATE[frac]}}}{{{value}}}")
        if ds in MACRO_DS and frac in MACRO_RATE:   # the drain's share of the makespan (App. J's CoQA sentence)
            share = 100.0 * m["drain"]["baseline_abs"] / m["makespan"]["baseline_abs"]
            macros.append(f"\\newcommand{{\\vpAbsDrainShare{MACRO_DS[ds]}{MACRO_RATE[frac]}}}{{{share:.0f}}}")
        offered = rate
        cells.append(f"{offered:.2f}")
        out.append(f"{NAMES.get(ds, ds)} & {frac} & " + " & ".join(cells) + r" \\")
    a.out.write_text("\n".join(out) + "\n")
    if a.macros:
        a.macros.write_text("\n".join(macros) + "\n")
    print(f"  {len(out)} absolute rows -> {a.out}" + (f"; {len(macros)-1} macros -> {a.macros}" if a.macros else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
