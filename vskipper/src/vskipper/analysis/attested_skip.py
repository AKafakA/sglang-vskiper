#!/usr/bin/env python3
"""The skip ratio a served arm actually ran, per phase, read from its attestation.

    attested_skip.py --cell Qwen=<root>/server_info.after.json ... --macros out.tex

`full_graph_routes.by_phase.<decode|prefill>.skip_ratio` is project_rows / layer_rows over every
routed-layer decision the server made in that phase: the fraction of decisions that took the cheap
path. It is what the checkpoint did on this suite under this arm, as opposed to what its training
target declared, and the two are compared in the Qwen appendix. Emits, per label,
\\vp<Label>SDecode and \\vp<Label>SPrefill to three decimals; --engagement-range adds the prefill
engagement estimate the regime switch held at the end of each listed cell, as a min/max pair.
--switch-cells Label=<cell base>,... reads each cell's own regime-switch counters (server_info.after minus .before, the
cells share one server) and emits, per cell in ascending offered rate (Low/Mid/High), \\vp<Label>DecodePasses<Rate>,
\\vp<Label>DecodeSkipPasses<Rate>, \\vp<Label>DecodeEngagedPct<Rate> (skip passes over all decode passes, 1 decimal) and
\\vp<Label>ProbePassPct<Rate> (routed prefill passes over all prefill passes, 1 decimal), plus the Min/Max of the probe
share. --pool Label=path emits \\vp<Label>KvPoolK, the server's K/V pool (max_total_num_tokens) in thousands. Fails on a
snapshot with no vp_runtime (an upstream arm has nothing to attest) or with a phase that made no decision.
"""
import argparse
import json
import re
import sys


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--cell", action="append", default=[], required=True, help="Label=path/to/server_info.after.json")
    ap.add_argument("--engagement-range", action="append", default=[],
                    help="Label=snap1,snap2,...: the regime switch's prefill engagement estimate (EMA) at the "
                         "end of each listed cell, emitted as \\vp<Label>PrefillEngagementMin / Max (2 decimals)")
    ap.add_argument("--switch-cells", action="append", default=[],
                    help="Label=cellbase1,cellbase2,...: per-cell decode/prefill switch counters (after minus before)")
    ap.add_argument("--pool", action="append", default=[], help="Label=path/to/server_info.json: K/V pool size in k tokens")
    ap.add_argument("--macros", required=True)
    args = ap.parse_args()
    lines = ["% GENERATED by attested_skip.py: per-phase skip ratio from the served arm's attestation"]
    for spec in args.cell:
        label, path = spec.split("=", 1)
        if not re.fullmatch(r"[A-Za-z]+", label):
            sys.exit(f"FATAL: label {label!r} must be letters only (it becomes a macro name)")
        info = json.load(open(path))
        states = info.get("internal_states") or []
        vp = states[0].get("vp_runtime") if states else None
        if not vp:
            sys.exit(f"FATAL {path}: no vp_runtime block -- nothing to attest (an upstream arm?)")
        phases = vp["model"]["flexidepth"]["full_graph_routes"]["by_phase"]
        for phase, name in (("decode", "SDecode"), ("prefill", "SPrefill")):
            rec = phases[phase]
            if rec["layer_rows"] == 0:
                sys.exit(f"FATAL {path}: phase {phase} made no routed-layer decision")
            lines.append(f"\\newcommand{{\\vp{label}{name}}}{{{rec['project_rows'] / rec['layer_rows']:.3f}}}")
    for spec in args.engagement_range:
        label, paths = spec.split("=", 1)
        if not re.fullmatch(r"[A-Za-z]+", label):
            sys.exit(f"FATAL: label {label!r} must be letters only (it becomes a macro name)")
        emas = []
        for path in paths.split(","):
            info = json.load(open(path))
            states = info.get("internal_states") or []
            vp = states[0].get("vp_runtime") if states else None
            if not vp:
                sys.exit(f"FATAL {path}: no vp_runtime block -- nothing to attest")
            est = vp["regime_switch"]["counters"]["prefill_engagement"]
            if est["samples"] == 0:
                sys.exit(f"FATAL {path}: the prefill engagement estimate took no sample")
            emas.append(est["ema"])
        lines.append(f"\\newcommand{{\\vp{label}PrefillEngagementMin}}{{{min(emas):.2f}}}")
        lines.append(f"\\newcommand{{\\vp{label}PrefillEngagementMax}}{{{max(emas):.2f}}}")
    for spec in args.switch_cells:
        label, bases = spec.split("=", 1)
        if not re.fullmatch(r"[A-Za-z]+", label):
            sys.exit(f"FATAL: label {label!r} must be letters only (it becomes a macro name)")
        cells = []
        for base in bases.split(","):
            rate = float(base.split("_qps")[1].split("_rep")[0].replace("p", "."))
            snaps = []
            for suffix in (".server_info.after.json", ".server_info.before.json"):
                info = json.load(open(base + suffix))
                states = info.get("internal_states") or []
                vp = states[0].get("vp_runtime") if states else None
                if not vp:
                    sys.exit(f"FATAL {base}{suffix}: no vp_runtime block -- nothing to attest")
                snaps.append(vp["regime_switch"]["counters"])
            after, before = snaps
            dec = {k: after["decode"][k] - before["decode"][k] for k in ("prod_allrun", "skip")}
            pre = {k: after["prefill"][k] - before["prefill"][k] for k in ("dense", "fd")}
            if dec["prod_allrun"] + dec["skip"] == 0 or pre["dense"] + pre["fd"] == 0:
                sys.exit(f"FATAL {base}: the cell recorded no decode or no prefill pass")
            cells.append((rate, dec, pre))
        if len(cells) != 3:
            sys.exit(f"FATAL {label}: --switch-cells names {len(cells)} cells, expected the three load points")
        probes = []
        for word, (rate, dec, pre) in zip(("Low", "Mid", "High"), sorted(cells)):
            passes = dec["prod_allrun"] + dec["skip"]
            probe = 100.0 * pre["fd"] / (pre["dense"] + pre["fd"]); probes.append(probe)
            lines.append(f"\\newcommand{{\\vp{label}DecodePasses{word}}}{{{passes:,}}}")
            lines.append(f"\\newcommand{{\\vp{label}DecodeSkipPasses{word}}}{{{dec['skip']:,}}}")
            lines.append(f"\\newcommand{{\\vp{label}DecodeEngagedPct{word}}}{{{100.0 * dec['skip'] / passes:.1f}}}")
            lines.append(f"\\newcommand{{\\vp{label}ProbePassPct{word}}}{{{probe:.1f}}}")
        lines.append(f"\\newcommand{{\\vp{label}ProbePassPctMin}}{{{min(probes):.1f}}}")
        lines.append(f"\\newcommand{{\\vp{label}ProbePassPctMax}}{{{max(probes):.1f}}}")
    for spec in args.pool:
        label, path = spec.split("=", 1)
        if not re.fullmatch(r"[A-Za-z]+", label):
            sys.exit(f"FATAL: label {label!r} must be letters only (it becomes a macro name)")
        info = json.load(open(path))
        pool = info["max_total_num_tokens"]
        if not pool:
            sys.exit(f"FATAL {path}: no max_total_num_tokens in the server info")
        lines.append(f"\\newcommand{{\\vp{label}KvPoolK}}{{{pool / 1e3:.0f}}}")
    open(args.macros, "w").write("\n".join(lines) + "\n")
    print(f"  {len(lines) - 1} attested-skip macros -> {args.macros}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
