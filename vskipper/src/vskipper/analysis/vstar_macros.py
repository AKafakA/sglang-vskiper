#!/usr/bin/env python3
"""Stage 3 (from a clone, no host): the V* macros, from `vstar_dump.py`'s JSON.

Emits one macro per swept arm giving the rule's crossover in thousands of resident K/V tokens, plus the two
served checkpoints. Pure stdlib, so the paper rebuilds from the evidence pack alone.

usage: vstar_macros.py sweep_vstar.json --out generated/sweep_vstar_macros.tex
"""
import argparse, json, re, sys

WORD = {"10": "Ten", "25": "Twentyfive", "50": "Fifty", "75": "Seventyfive"}
FIXED = {"vskipper": "vpVstarServed", "vskipper_qwen3_4b": "vpVstarQwenLearned"}


def macro_name(arm: str) -> str:
    """integrated_randomskip[_qwen3_4b]_r50_d75 -> vpVstar[Qwen]RFiftyDSeventyfive."""
    if arm in FIXED:
        return FIXED[arm]
    m = re.fullmatch(r"integrated_randomskip(_qwen3_4b)?_r(\d+)_d(\d+)", arm)
    if not m:
        return ""
    qwen, rate, depth = m.group(1), m.group(2), m.group(3)
    if rate not in WORD or depth not in WORD:
        raise SystemExit(f"unmapped rate/depth in {arm}: add it to WORD")
    return f"vpVstar{'Qwen' if qwen else ''}R{WORD[rate]}D{WORD[depth]}"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("json", help="output of vstar_dump.py")
    ap.add_argument("--out", required=True)
    ap.add_argument("--attested", action="append", default=[], metavar="Label=macros.tex:\\vpMacro:Lr",
                    help="V* by the same rule for an ATTESTED skip ratio read from a generated macro file "
                         "(e.g. QwenAttested=generated/attested_skip_macros.tex:vpQwenSDecode:18), emitted as \\vpVstar<Label>")
    args = ap.parse_args()

    d = json.load(open(args.json))
    lines = ["% GENERATED by vstar_macros.py from the tree's roofline rule (vstar_dump.py): "
             "V* per arm, in k resident K/V tokens."]
    n = 0
    for arm, rec in d["arms"].items():
        name = macro_name(arm)
        if not name:
            continue
        lines.append(f"\\newcommand{{\\{name}}}{{{round(rec['vstar'] / 1000):d}}}")
        n += 1
    if not n:
        raise SystemExit(f"no arms matched in {args.json}")
    # the fixed per-step tax tau the rule scales by routed depth: one value per routed-layer count
    taus = sorted({(rec["Lr"], round(rec["tau_ms"], 2)) for rec in d["arms"].values()})
    for lr, tau in taus:
        lines.append(f"\\newcommand{{\\vpVstarTauMsL{lr}}}{{{tau:.2f}}}".replace(f"L{lr}", "L" + {16: "Sixteen", 18: "Eighteen"}.get(lr, str(lr))))
    peaks = d.get("device_peaks_A100")
    if peaks:
        lines.append(f"\\newcommand{{\\vpVstarPeakTflops}}{{{peaks[0]:.0f}}}")
        lines.append(f"\\newcommand{{\\vpVstarPeakTbps}}{{{peaks[1] / 1000:.2f}}}")
    for spec in args.attested:
        # V* = tau * BW / (s * Lr * b) with the dump's own tau for that Lr and its A100 bandwidth, b = 4 KB per row-layer
        label, rest = spec.split("=", 1); path, macro, lr = rest.rsplit(":", 2); lr = int(lr)
        hit = re.search(r"\\newcommand\{\\" + re.escape(macro) + r"\}\{([0-9.]+)\}", open(path).read())
        if not hit:
            raise SystemExit(f"{path}: no macro {macro}")
        s_att = float(hit.group(1))
        tau = {rec["Lr"]: rec["tau_ms"] for rec in d["arms"].values()}.get(lr)
        if tau is None or not peaks:
            raise SystemExit(f"no tau for Lr={lr} or no device peaks in {args.json}")
        vstar = tau * 1e-3 * peaks[1] * 1e9 / (s_att * lr * 4096)
        lines.append(f"\\newcommand{{\\vpVstar{label}}}{{{round(vstar / 1000):d}}}")
    open(args.out, "w").write("\n".join(lines) + "\n")
    print(f"  {n} V* macros -> {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
