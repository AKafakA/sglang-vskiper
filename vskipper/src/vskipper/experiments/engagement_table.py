#!/usr/bin/env python3
"""Engagement per headline cell (critique of plan v5, δ1): what fraction of the treatment arm's passes ran the
routed body, per leg, read from the runner's own gate block ("prefill passes (scheduler)", "routed body (fd)",
"dense body", "routed work during the run", "skip body (routed)", "all-RUN (NO skipping)"). Prefill routed = fd /
(fd + dense). Decode routed = (skip - fd) / (all_run + skip - fd): the runner's "skip body" count includes the
prefill fd passes, so they are removed before the decode fraction is formed. Means over the reps present.
usage: engagement_table.py <campaign-root> --treatment integrated_it4 --knee gsm8k=11 ... --rows out.tex --macros out.tex
"""
from __future__ import annotations
import argparse, re, statistics as st, sys
from pathlib import Path

NAMES = {"gsm8k": "GSM8K", "bbh_cot": "BBH", "coqa": "CoQA"}
MACRO_DS = {"gsm8k": "Gsm", "bbh_cot": "Bbh", "coqa": "Coqa"}
MACRO_RATE = {"0.75": "Low", "0.95": "Mid", "1.25": "High"}


def parse(log: Path) -> dict[str, tuple[float, float, int, int]]:
    out, cell, vals = {}, None, {}
    for line in log.read_text(errors="replace").splitlines():
        m = re.search(r"([a-z0-9_]+_eqw_r[0-9p]+)_qps", line)
        if m and ("COMPLETED" in line or "workload=" in line):
            cell = m.group(1)
        for key, pat in (("fd", r"routed body \(fd\)\s*:\s*(\d+)"), ("dense", r"dense body\s*:\s*(\d+)"),
                         ("skip", r"skip body \(routed\)\s*:\s*(\d+)"), ("allrun", r"all-RUN \(NO skipping\)\s*:\s*(\d+)")):
            mm = re.search(pat, line)
            if mm:
                vals[key] = int(mm.group(1))
        if "COMPLETED workload=" in line and cell and all(k in vals for k in ("fd", "dense", "skip", "allrun")):
            fd, dense, skip, allrun = vals["fd"], vals["dense"], vals["skip"], vals["allrun"]
            dec_routed = max(skip - fd, 0); dec_total = allrun + dec_routed
            out[cell] = (100.0 * fd / max(fd + dense, 1), 100.0 * dec_routed / max(dec_total, 1), fd + dense, dec_total)
            vals = {}
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("root", type=Path); ap.add_argument("--treatment", default="integrated_it4")
    ap.add_argument("--knee", action="append", default=[]); ap.add_argument("--rows", type=Path, required=True)
    ap.add_argument("--macros", type=Path, default=None)
    a = ap.parse_args()
    knees = {k: float(v) for k, v in (x.split("=", 1) for x in a.knee)}
    per: dict[tuple[str, str], list[tuple[float, float]]] = {}
    for log in sorted(a.root.glob(f"rep*/*/{a.treatment}/runner.log")):
        ds = log.parent.parent.name
        for cell, (pre, dec, _, _) in parse(log).items():
            per.setdefault((ds, cell), []).append((pre, dec))
    if not per:
        sys.exit(f"no engagement blocks found under {a.root}")
    rows, macros = [], ["% GENERATED by vskipper/src/vskipper/experiments/engagement_table.py -- routed-pass fractions per cell (means over reps)."]
    def _rate(cell):
        """Sort rows by offered rate, not by label: r10p45 < r13p75 < r8p25 lexically, which
        printed the three GSM8K rows out of order."""
        return float(cell.split("_r")[-1].replace("p", "."))

    for (ds, cell), v in sorted(per.items(), key=lambda kv: (list(NAMES).index(kv[0][0]) if kv[0][0] in NAMES else 9, _rate(kv[0][1]))):
        rate = float(cell.split("_r")[-1].replace("p", "."))
        frac = f"{rate/knees[ds]:.2f}" if ds in knees else "--"
        pre = st.fmean(x for x, _ in v); dec = st.fmean(y for _, y in v)
        rows.append(f"{NAMES.get(ds, ds)} & {frac} & {len(v)} & {pre:.0f} & {dec:.1f} \\\\")
        if ds in MACRO_DS and frac in MACRO_RATE:
            macros.append(f"\\newcommand{{\\vpEngPre{MACRO_DS[ds]}{MACRO_RATE[frac]}}}{{{pre:.0f}}}")
            macros.append(f"\\newcommand{{\\vpEngDec{MACRO_DS[ds]}{MACRO_RATE[frac]}}}{{{dec:.1f}}}")
    a.rows.write_text("\n".join(rows) + "\n")
    if a.macros:
        a.macros.write_text("\n".join(macros) + "\n")
    print(f"  {len(rows)} engagement rows -> {a.rows}" + (f"; {len(macros)-1} macros" if a.macros else ""))
    for r in rows: print("   ", r)
    return 0


if __name__ == "__main__":
    sys.exit(main())
